bool app_has_kconfig(const fs::path& root) {
    std::error_code ec;
    return fs::is_regular_file(root / "Kconfig", ec);
}

std::string render_merged_kconfig(const std::string& project_name,
                                  const fs::path& navhal_kconfig,
                                  const std::vector<KconfigDep>& deps,
                                  const fs::path& app_kconfig) {
    std::ostringstream os;
    os << "# Auto-generated by `nav build`: the merged Kconfig tree for this project.\n"
       << "# Do not edit; edit the app's Kconfig and .config instead.\n"
       << "mainmenu \"" << project_name << " configuration\"\n\n"
       << "source " << q(navhal_kconfig) << "\n";
    for (const auto& d : deps) os << "source " << q(d.kconfig) << "\n";
    os << "\nmenu \"" << kAppMenu << "\"\n"
       << "source " << q(app_kconfig) << "\n"
       << "endmenu\n";
    return os.str();
}

std::string render_app_autoconf(const std::vector<AppSymbol>& syms) {
    std::ostringstream os;
    os << "/* Auto-generated by `nav build` from the app's Kconfig and .config. */\n"
       << "#ifndef NAV_APP_AUTOCONF_H\n#define NAV_APP_AUTOCONF_H\n\n";
    for (const auto& s : syms) {
        if (s.type == "bool") {
            if (s.value == "y") os << "#define CONFIG_" << s.name << " 1\n";
            else                os << "/* CONFIG_" << s.name << " is not set */\n";
        } else if (s.type == "string") {
            os << "#define CONFIG_" << s.name << " \"" << c_escape(s.value) << "\"\n";
        } else { // int, hex
            os << "#define CONFIG_" << s.name << " " << (s.value.empty() ? "0" : s.value) << "\n";
        }
    }
    os << "\n#endif /* NAV_APP_AUTOCONF_H */\n";
    return os.str();
}

std::string render_app_cmake(const std::vector<AppSymbol>& syms, const fs::path& autoconf) {
    std::ostringstream os;
    os << "# Auto-generated by `nav build`: the app's Kconfig symbols as CMake variables.\n"
       << "set(NAV_APP_AUTOCONF " << q(autoconf) << ")\n";
    for (const auto& s : syms) {
        os << "set(CONFIG_" << s.name << " ";
        if (s.type == "bool")        os << (s.value == "y" ? "ON" : "OFF");
        else if (s.type == "string") os << "\"" << cmake_escape(s.value) << "\"";
        else                         os << (s.value.empty() ? "0" : s.value);
        os << ")\n";
    }
    return os.str();
}

std::string kconfig_validator_script() {
    return R"PY(# Generated by nav. Validates the app's .config against the merged Kconfig tree.
import json, os, sys
import kconfiglib

kconfig, config, out_config, out_syms, app_menu = sys.argv[1:6]
os.environ["KCONFIG_CONFIG"] = config

kb = kconfiglib.Kconfig(kconfig, warn_to_stderr=False)
kb.warn_assign_undef = True  # off by default: an unknown CONFIG_X would be dropped silently
before = len(kb.warnings)
if os.path.exists(config):
    kb.load_config(config)

errors, warnings = [], []
for w in kb.warnings[before:]:
    low = w.lower()
    if "undefined symbol" in low or "not a valid value" in low or "is invalid for" in low or "malformed" in low:
        errors.append(w)
    else:
        warnings.append(w)
if errors:
    for e in errors:
        print("error: " + e)
    sys.exit(2)
for w in warnings:
    print("warning: " + w)

def in_app(node):
    p = node.parent
    while p is not None:
        if p.prompt and p.prompt[0] == app_menu and not isinstance(p.item, kconfiglib.Symbol):
            return True
        p = p.parent
    return False

syms = []
for sym in kb.unique_defined_syms:
    if sym.type not in (kconfiglib.BOOL, kconfiglib.INT, kconfiglib.HEX, kconfiglib.STRING):
        continue
    if not any(in_app(n) for n in sym.nodes):
        continue
    syms.append({"name": sym.name, "type": kconfiglib.TYPE_TO_STR[sym.type],
                 "value": sym.str_value})

kb.write_config(out_config)
with open(out_syms, "w") as f:
    json.dump(syms, f)
)PY";
}

fs::path write_merged_kconfig(const fs::path& root, const ProjectConfig& cfg,
                              const std::vector<ResolvedLib>& libs, const fs::path& navhal_dir) {
    std::vector<KconfigDep> deps;
    for (const auto& l : libs) {
        std::error_code ec;
        if (fs::is_regular_file(l.src / "Kconfig", ec)) deps.push_back({l.name, l.src / "Kconfig"});
    }
    const fs::path build = root / "build";
    std::error_code ec;
    fs::create_directories(build, ec);
    const fs::path out = build / "nav-Kconfig";
    const std::string text = render_merged_kconfig(
        cfg.project_name.empty() ? "app" : cfg.project_name,
        fs::absolute(navhal_dir) / "Kconfig", deps, fs::absolute(root / "Kconfig"));
    if (!write_if_changed(out, text)) return {};
    return out;
}

bool prepare_app_kconfig(IExecutionContext& ctx, const fs::path& root, const ProjectConfig& cfg,
                         const std::vector<ResolvedLib>& libs, const fs::path& navhal_dir,
                         std::string* error, std::vector<std::string>* warnings) {
    auto fail = [&](const std::string& m) { if (error) *error = m; return false; };

    const fs::path merged = write_merged_kconfig(root, cfg, libs, navhal_dir);
    if (merged.empty()) return fail("could not write build/nav-Kconfig");

    const fs::path build = root / "build";
    const fs::path script = build / "nav-kconfig.py";
    const fs::path out_config = build / "nav.config";
    const fs::path out_syms = build / "nav-app-symbols.json";
    if (!write_if_changed(script, kconfig_validator_script()))
        return fail("could not write " + script.string());

    const fs::path empty_stub = fs::absolute(build / "nav-empty.Kconfig");
    if (!write_if_changed(empty_stub, "# Intentionally empty: stands in for NavHAL under $(NAVHAL_KCONFIG).\n"))
        return fail("could not write " + empty_stub.string());

    // Resolved against the NavHAL clone, as for every other kconfiglib run; and
    // NAVHAL_KCONFIG pointed at an empty stub (see EnvGuard).
    EnvGuard srctree("srctree", fs::absolute(navhal_dir).string());
    EnvGuard no_navhal("NAVHAL_KCONFIG", empty_stub.string());

    auto res = ctx.execute({"python3", script.string(), merged.string(),
                            (root / ".config").string(), out_config.string(),
                            out_syms.string(), kAppMenu},
                           root.string(), /*silent=*/true);
    std::vector<std::string> lines;
    {
        std::istringstream is(res.output);
        std::string line;
        while (std::getline(is, line)) lines.push_back(line);
    }
    if (res.exit_code != 0) {
        std::string msg;
        bool kc_err = false;
        for (const auto& l : lines)
            if (l.rfind("error: ", 0) == 0) { kc_err = true; msg += (msg.empty() ? "" : "\n") + l.substr(7); }
        if (kc_err) msg = ".config does not match the Kconfig tree:\n" + msg;
        else msg = "kconfiglib failed (is it installed for nav's python? pip install kconfiglib):\n" + res.output;
        return fail(msg);
    }
    if (warnings)
        for (const auto& l : lines)
            if (l.rfind("warning: ", 0) == 0) warnings->push_back(l.substr(9));

    std::vector<AppSymbol> syms;
    try {
        std::ifstream f(out_syms);
        nlohmann::json j = nlohmann::json::parse(f);
        for (const auto& e : j)
            syms.push_back({e.at("name").get<std::string>(), e.at("type").get<std::string>(),
                            e.at("value").get<std::string>()});
    } catch (const std::exception& e) {
        return fail(std::string("could not read the app symbol list: ") + e.what());
    }

    const fs::path autoconf = build / "app_autoconf.h";
    if (!write_if_changed(autoconf, render_app_autoconf(syms)) ||
        !write_if_changed(build / "nav-app-kconfig.cmake", render_app_cmake(syms, fs::absolute(autoconf))))
        return fail("could not write the generated app config files in build/");
    return true;
}

