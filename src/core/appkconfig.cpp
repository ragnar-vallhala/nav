constexpr const char* kAppMenu = "Application options";

std::string q(const fs::path& p) { return "\"" + p.generic_string() + "\""; }

std::string c_escape(const std::string& s) {
    std::string o;
    for (char c : s) {
        switch (c) {
            case '\\': o += "\\\\"; break;
            case '"':  o += "\\\""; break;
            case '\n': o += "\\n"; break;
            case '\r': o += "\\r"; break;
            case '\t': o += "\\t"; break;
            default:   o += c;
        }
    }
    return o;
}

std::string cmake_escape(const std::string& s) {
    std::string o;
    for (char c : s) {
        if (c == '\\' || c == '"' || c == '$') o += '\\';
        o += c;
    }
    return o;
}

void set_env(const char* key, const std::string& val) {
#ifdef _WIN32
    ::_putenv_s(key, val.c_str());
#else
    ::setenv(key, val.c_str(), 1);
#endif
}

void clear_env(const char* key) {
#ifdef _WIN32
    ::_putenv_s(key, "");
#else
    ::unsetenv(key);
#endif
}

// The merged tree sources NavHAL's Kconfig itself, so a dependency that also
// osources it through $(NAVHAL_KCONFIG) (vaios) would define every NavHAL
// symbol twice. Pointing the variable at an empty file turns that osource into a no-op (an empty value would resolve to the srctree directory itself). Restored
// on scope exit so nothing leaks into the cmake run that follows.
struct EnvGuard {
    std::string key;
    std::string old;
    bool had = false;
    EnvGuard(const char* k, const std::string& v) : key(k) {
        if (const char* e = std::getenv(k)) { had = true; old = e; }
        set_env(k, v);
    }
    ~EnvGuard() { if (had) set_env(key.c_str(), old); else clear_env(key.c_str()); }
};

bool write_if_changed(const fs::path& p, const std::string& text) {
    {
        std::ifstream in(p, std::ios::binary);
        if (in) {
            std::stringstream ss;
            ss << in.rdbuf();
            if (ss.str() == text) return true;
        }
    }
    std::ofstream f(p, std::ios::binary);
    if (!f) return false;
    f << text;
    return f.good();
}

