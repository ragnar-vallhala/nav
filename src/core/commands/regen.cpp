#include "nav/core/appbuild.hpp"
#include "nav/core/command.hpp"
#include "nav/core/config.hpp"
#include "nav/core/ui.hpp"

#include <filesystem>
#include <fstream>
#include <sstream>

namespace fs = std::filesystem;

namespace nav::core {

int RegenCommand::run(IExecutionContext& /*ctx*/, const std::vector<std::string>& /*args*/) {
    auto root = find_project_root();
    if (!root) {
        ui::error("No nav.toml found in this directory or any parent.");
        return 1;
    }
    fs::current_path(*root);

    auto cfg = load_project_config(*root);
    if (!cfg) {
        ui::error("Failed to parse 'nav.toml'.");
        return 1;
    }
    if (cfg->is_library()) {
        ui::error("'nav regen' only supports executable projects.");
        return 1;
    }
    if (cfg->project_name.empty()) {
        ui::error("'nav.toml' has no [project].name.");
        return 1;
    }

    const fs::path lists = "CMakeLists.txt";
    const fs::path backup = "CMakeLists.txt.old";
    std::error_code ec;
    if (fs::exists(lists, ec)) {
        std::ostringstream ss;
        ss << std::ifstream(lists).rdbuf();
        const std::string text = ss.str();
        if (!cmakelists_is_nav_generated_app(text)) {
            ui::error("CMakeLists.txt was not generated by nav; leaving it alone.");
            return 1;
        }
        if (cmakelists_supports_app_build(text)) {
            ui::success("CMakeLists.txt is already current (nothing to do).");
            return 0;
        }
        if (fs::exists(backup, ec)) {
            ui::error("CMakeLists.txt.old already exists; move it aside and re-run.");
            return 1;
        }
        fs::rename(lists, backup, ec);
        if (ec) {
            ui::error("Could not back up CMakeLists.txt: " + ec.message());
            return 1;
        }
        ui::info("Saved the previous CMakeLists.txt as CMakeLists.txt.old.");
    }

    std::ofstream out(lists);
    out << render_app_cmakelists(cfg->project_name);
    if (!out.good()) {
        ui::error("Failed to write CMakeLists.txt.");
        return 1;
    }
    ui::success("CMakeLists.txt regenerated from nav's current template.");
    return 0;
}

} // namespace nav::core
