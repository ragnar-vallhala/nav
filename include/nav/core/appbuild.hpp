#pragma once

#include "nav/core/config.hpp"

#include <filesystem>
#include <optional>
#include <string>
#include <vector>

namespace nav::core {

// Match a project-relative path against a glob. Separators are '/' (a '\' in
// either argument is treated as one, so Windows-style input works). Within a
// segment '*' matches any run of characters and '?' one character, never a
// separator; a whole segment '**' matches zero or more directories. Matching
// is case-sensitive and covers the whole path.
bool glob_match(const std::string& pattern, const std::string& path);

// A fully expanded app build, ready to render.
struct AppBuildPlan {
    std::vector<std::string> sources;       // absolute, '/'-separated, sorted
    std::vector<std::string> include_dirs;  // absolute, '/'-separated
    std::vector<std::string> defines;
    std::vector<std::string> c_flags;
    std::optional<int> c_standard;
    std::string output;                     // firmware file name; empty = project name
    std::string linker_fragment;            // absolute, '/'-separated; empty = none
    std::string libc = "none";
    std::vector<std::string> libs;
    struct FileFlags {
        std::vector<std::string> files;     // absolute, '/'-separated, sorted
        std::vector<std::string> flags;
    };
    std::vector<FileFlags> file_flags;      // in nav.toml order
};

// Expand cfg.build against cfg.root: sources globs minus excludes (sorted,
// deduplicated), then match each file_flags rule against the surviving
// sources. Returns nullopt with `error` set when a sources pattern or a
// file_flags rule matches nothing, or when no source remains.
std::optional<AppBuildPlan> plan_app_build(const ProjectConfig& cfg, std::string& error);

// Render the plan as build/nav-app.cmake (see templates/cmakelists.txt.in).
std::string render_app_cmake(const AppBuildPlan& plan);

// True when a CMakeLists.txt includes nav-app.cmake, i.e. was generated from a
// template that understands [build] settings.
bool cmakelists_supports_app_build(const std::string& cmakelists_text);

// True when a CMakeLists.txt understands build variants (renamed firmware, an
// alternative .config), i.e. was generated by a nav that has them.
bool cmakelists_supports_variants(const std::string& cmakelists_text);

// True when a CMakeLists.txt looks generated by nav for an executable app, and
// so is safe for `nav regen` to replace.
bool cmakelists_is_nav_generated_app(const std::string& cmakelists_text);

// The app CMakeLists.txt from the embedded template for `project_name`.
std::string render_app_cmakelists(const std::string& project_name);

} // namespace nav::core
